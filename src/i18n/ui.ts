const DICT: Record<Lang, Record<UIKey, string>> = { ko, en, ja };

/** 테스트용: 언어별 사전 키 패리티 검사 */
export function dictKeys(lang: Lang): UIKey[] {
  return Object.keys(DICT[lang]) as UIKey[];
}

export function tr(lang: Lang, key: UIKey, vars?: Record<string, string | number>): string {
  let s: string = DICT[lang][key] ?? ko[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replace(`{${k}}`, String(v));
    }
  }
  return s;
}
